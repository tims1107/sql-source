select * from    
(SELECT 
    r.order_number,
    TO_CHAR(r.release_date_time, 'DD-MON-YY HH24:MI') AS release_datetime,
    r.last_update_time,
    ROUND(
        EXTRACT(DAY FROM (r.last_update_time - r.release_date_time)) * 24 + 
        EXTRACT(HOUR FROM (r.last_update_time - r.release_date_time)) + 
        EXTRACT(MINUTE FROM (r.last_update_time - r.release_date_time)) / 60, 2
    ) AS hour_diff
FROM asr_process_run a
JOIN results_sent_log r ON a.order_number = r.order_number 
    AND a.result_test_code = r.result_test_code
    AND source = 'IL'
) where last_update_time > '15-OCT-25 03.48.12.306700000 PM'
order by hour_diff desc
;

SELECT 
    TO_CHAR(TRUNC(r.release_date_time), 'DD-MON-YY') AS release_date,
    r.order_number,
    TO_CHAR(r.release_date_time, 'HH24:MI') AS release_time,
    r.last_update_time,
    ROUND(
        EXTRACT(DAY FROM (r.last_update_time - r.release_date_time)) * 24 + 
        EXTRACT(HOUR FROM (r.last_update_time - r.release_date_time)) + 
        EXTRACT(MINUTE FROM (r.last_update_time - r.release_date_time)) / 60, 2
    ) AS hour_diff
FROM asr_process_run a
JOIN results_sent_log r ON a.order_number = r.order_number 
    AND a.result_test_code = r.result_test_code
    AND source = 'IL'
WHERE r.last_update_time > TIMESTAMP '2025-06-01 23:48:12.306700'
ORDER BY  hour_diff DESC;