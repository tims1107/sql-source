-- Create the PDF_REPORTS table
CREATE TABLE PDF_REPORTS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FILENAME VARCHAR2(255) NOT NULL,
    REPORT_TYPE VARCHAR2(50) NOT NULL,
    REGION VARCHAR2(50),
    CONTENT_TYPE VARCHAR2(100) NOT NULL,
    FILE_SIZE NUMBER NOT NULL,
    PDF_DATA BLOB NOT NULL,
    CREATED_DATE TIMESTAMP NOT NULL,
    CREATED_BY VARCHAR2(100),
    DESCRIPTION VARCHAR2(500),
    PATIENT_COUNT NUMBER,
    CHECKSUM VARCHAR2(64)
);

-- Create indexes for performance optimization
CREATE INDEX idx_pdf_report_type_region ON PDF_REPORTS (REPORT_TYPE, REGION);
CREATE INDEX idx_pdf_report_created_date ON PDF_REPORTS (CREATED_DATE);
CREATE INDEX idx_pdf_report_filename ON PDF_REPORTS (FILENAME);

-- Add comments for documentation
COMMENT ON TABLE PDF_REPORTS IS 'Stores PDF report binary data with metadata for retrieval and management';
COMMENT ON COLUMN PDF_REPORTS.ID IS 'Primary key - auto-generated identity';
COMMENT ON COLUMN PDF_REPORTS.FILENAME IS 'Original filename of the PDF report';
COMMENT ON COLUMN PDF_REPORTS.REPORT_TYPE IS 'Type of report (e.g., PatientResults)';
COMMENT ON COLUMN PDF_REPORTS.REGION IS 'Region for the report (e.g., East, South)';
COMMENT ON COLUMN PDF_REPORTS.CONTENT_TYPE IS 'MIME type of the file (default: application/pdf)';
COMMENT ON COLUMN PDF_REPORTS.FILE_SIZE IS 'Size of the PDF file in bytes';
COMMENT ON COLUMN PDF_REPORTS.PDF_DATA IS 'Binary data of the PDF file';
COMMENT ON COLUMN PDF_REPORTS.CREATED_DATE IS 'Timestamp when the report was created';
COMMENT ON COLUMN PDF_REPORTS.CREATED_BY IS 'User or system that created the report';
COMMENT ON COLUMN PDF_REPORTS.DESCRIPTION IS 'Optional description of the report';
COMMENT ON COLUMN PDF_REPORTS.PATIENT_COUNT IS 'Number of patients included in the report';
COMMENT ON COLUMN PDF_REPORTS.CHECKSUM IS 'SHA-256 checksum for duplicate detection';

